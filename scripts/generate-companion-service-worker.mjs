#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REQUIRED_SHELL_FILES = [
  'index.html',
  'manifest.webmanifest',
  'companion-icon-192.png',
  'companion-icon-512.png',
];
const COMPANION_ENTRY_FILE = 'c/index.html';
const PRECACHE_SHELL_FILES = [
  COMPANION_ENTRY_FILE,
  'manifest.webmanifest',
  'companion-icon-192.png',
  'companion-icon-512.png',
];

const COMPANION_ENTRY_SUFFIXES = [
  'src/features/surfaces/CompanionShell.tsx',
  'src/features/surfaces/CompanionHome.tsx',
];
const COMPANION_PRECACHE_BUDGET_BYTES = 5 * 1024 * 1024;

function shouldPrecacheAsset(file) {
  if (!/\.woff2?$/.test(file)) return true;
  // Puntovivo ships EN/ES. Cache only the compressed Latin subsets needed by
  // those locales; every other font remains a normal online browser request.
  return file.endsWith('.woff2') && /-latin(?:-ext)?-/.test(file);
}

function selectCompanionBuildFiles(manifest) {
  const entries = Object.entries(manifest);
  const entryKey = entries.find(([, value]) => value?.isEntry)?.[0];
  const companionKeys = COMPANION_ENTRY_SUFFIXES.map(suffix =>
    entries.find(([key, value]) => key.endsWith(suffix) || value?.src?.endsWith(suffix))?.[0]
  );
  if (!entryKey || companionKeys.some(key => !key)) {
    throw new Error('Companion PWA manifest is missing the app or Companion entries');
  }

  const files = new Set();
  const pending = [entryKey, ...companionKeys];
  const visited = new Set();
  while (pending.length > 0) {
    const key = pending.pop();
    if (!key || visited.has(key)) continue;
    visited.add(key);
    const entry = manifest[key];
    if (!entry || typeof entry.file !== 'string') {
      throw new Error(`Companion PWA manifest entry is invalid: ${key}`);
    }
    files.add(entry.file);
    for (const file of [...(entry.css ?? []), ...(entry.assets ?? [])]) {
      if (shouldPrecacheAsset(file)) files.add(file);
    }
    // Follow static imports only. Following the root's dynamic imports would
    // download every admin route (PDF, XLSX and CodeMirror) into a phone PWA.
    pending.push(...(entry.imports ?? []));
  }
  return [...files];
}

function renderWorker(cacheName, precachePaths) {
  return `/* Generated by scripts/generate-companion-service-worker.mjs. */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_PATHS = ${JSON.stringify(precachePaths, null, 2)};
const PRECACHE_SET = new Set(PRECACHE_PATHS);

self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE_NAME).then(cache => cache.addAll(PRECACHE_PATHS)));
  self.skipWaiting();
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys().then(keys =>
      Promise.all(
        keys
          .filter(key => key.startsWith('puntovivo-companion-') && key !== CACHE_NAME)
          .map(key => caches.delete(key))
      )
    ).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Authenticated tRPC, SSE and health traffic is always network-only.
  if (url.pathname === '/api' || url.pathname.startsWith('/api/')) return;

  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('/c/index.html')));
    return;
  }

  if (PRECACHE_SET.has(url.pathname)) {
    event.respondWith(caches.match(request).then(cached => cached || fetch(request)));
  }
});
`;
}

async function writeCompanionEntrypoint(dist) {
  const rootHtml = await readFile(join(dist, 'index.html'), 'utf8');
  if (/<base\s/i.test(rootHtml)) {
    throw new Error('Companion PWA root entry must preserve the portable relative base');
  }
  const companionHtml = rootHtml.replace(/<head(\s[^>]*)?>/i, match => `${match}\n    <base href="/" />`);
  if (companionHtml === rootHtml) {
    throw new Error('Companion PWA root entry has no head element');
  }
  const outputPath = join(dist, COMPANION_ENTRY_FILE);
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, companionHtml, 'utf8');
}

export async function generateCompanionServiceWorker(distDirectory) {
  const dist = resolve(distDirectory);
  for (const file of REQUIRED_SHELL_FILES) {
    let fileStats;
    try {
      fileStats = await stat(join(dist, file));
    } catch (error) {
      throw new Error(`Companion PWA asset is missing: ${file}`, { cause: error });
    }
    if (!fileStats.isFile()) throw new Error(`Companion PWA asset is not a file: ${file}`);
  }
  // Electron loads the root production index as a file and therefore needs
  // Vite's portable ./assets base. The installed HTTP PWA starts at /c/, where
  // those same relative URLs would incorrectly resolve under /c/assets. Emit a
  // dedicated nested document with a root base instead of weakening either
  // runtime's asset contract.
  await writeCompanionEntrypoint(dist);

  let manifest;
  try {
    manifest = JSON.parse(await readFile(join(dist, '.vite', 'manifest.json'), 'utf8'));
  } catch (error) {
    throw new Error('Companion PWA Vite manifest is missing or invalid', { cause: error });
  }
  const assetFiles = selectCompanionBuildFiles(manifest);

  const relativeFiles = [...new Set([...PRECACHE_SHELL_FILES, ...assetFiles])].sort();
  const digest = createHash('sha256');
  let precacheBytes = 0;
  for (const file of relativeFiles) {
    const contents = await readFile(join(dist, file));
    precacheBytes += contents.byteLength;
    digest.update(file);
    digest.update('\0');
    digest.update(contents);
    digest.update('\0');
  }
  if (precacheBytes > COMPANION_PRECACHE_BUDGET_BYTES) {
    throw new Error(
      `Companion PWA precache exceeds ${COMPANION_PRECACHE_BUDGET_BYTES} bytes: ${precacheBytes}`
    );
  }

  const cacheName = `puntovivo-companion-${digest.digest('hex').slice(0, 16)}`;
  const precachePaths = relativeFiles.map(file => `/${file}`);
  const outputPath = join(dist, 'service-worker.js');
  await writeFile(outputPath, renderWorker(cacheName, precachePaths), 'utf8');
  return { cacheName, outputPath, precachePaths, precacheBytes };
}

const isEntrypoint =
  process.argv[1] &&
  basename(process.argv[1]) === basename(fileURLToPath(import.meta.url)) &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url;

if (isEntrypoint) {
  const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  await generateCompanionServiceWorker(resolve(repoRoot, 'apps', 'web', 'dist'));
}
